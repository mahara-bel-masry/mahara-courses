import numpy as np
hours = np.array([1, 2, 2, 3, 4, 4, 5, 6, 6, 7, 8, 9])
score = np.array([52, 55, 50, 61, 66, 63, 70, 74, 72, 80, 83, 88])
dx = hours - hours.mean(); dy = score - score.mean()
cov = (dx * dy).sum() / (len(hours) - 1)
r_hand = (dx * dy).sum() / np.sqrt((dx**2).sum() * (dy**2).sum())
print("covariance", round(cov, 3))
print("r by hand", round(r_hand, 4))
print("r numpy", round(np.corrcoef(hours, score)[0, 1], 4))
print("r squared", round(r_hand**2, 4))
slope, intercept = np.polyfit(hours, score, 1)
print("line", round(slope, 3), round(intercept, 3))
print("predict 5 hours", round(slope * 5 + intercept, 2))
print("predict 30 hours", round(slope * 30 + intercept, 2))

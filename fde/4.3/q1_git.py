import subprocess, tempfile, os
d = tempfile.mkdtemp()
os.chdir(d)
def g(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return (r.stdout + r.stderr).strip()
g("git init -q -b main")
g("git config user.email a@b.c && git config user.name demo")
open("a.txt", "w").write("one\n")
g("git add a.txt && git commit -q -m first")
print(g("git log --oneline | wc -l"))
g("git checkout -q -b feature")
open("a.txt", "a").write("two\n")
g("git commit -q -am second")
g("git checkout -q main")
g("git merge -q feature")
print(g("git branch --show-current"))
print(g("git log --oneline | wc -l"))
print(open("a.txt").read().split())

import subprocess, tempfile, os
d = tempfile.mkdtemp()
os.chdir(d)
def g(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return (r.stdout + r.stderr).strip()
g("git init -q -b main")
g("git config user.email a@b.c")
g("git config user.name demo")
open("etl.sql", "w").write("SELECT 1;\n")
g("git add . && git commit -q -m base")
g("git checkout -q -b dev")
open("etl.sql", "w").write("SELECT 2;\n")
g("git commit -q -am dev")
g("git checkout -q main")
open("etl.sql", "w").write("SELECT 3;\n")
g("git commit -q -am main")
print(g("git merge dev").count("CONFLICT"))
